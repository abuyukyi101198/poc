import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { normalizeLldpTopology } from '../js/lldp-adapter.js';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const d3Dir = resolve(scriptDir, '..');
const sourceDir = resolve(d3Dir, 'data', 'lldp');
const outputDir = resolve(d3Dir, 'data', 'generated', 'lldp');
const maasEnrichmentPath = resolve(d3Dir, 'data', 'generated', 'maas', 'tor3-maas-ui-enrichment.json');

function fixtureId(name) {
  const slug = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  if (!slug) throw new Error(`Cannot create a fixture id from dataset name "${name}".`);
  return `lldp-${slug}`;
}

async function readJson(path) {
  try {
    return JSON.parse(await readFile(path, 'utf8'));
  } catch (error) {
    throw new Error(`Could not read JSON from ${path}: ${error.message}`);
  }
}

async function readOptionalJson(path) {
  try {
    return JSON.parse(await readFile(path, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw new Error(`Could not read JSON from ${path}: ${error.message}`);
  }
}

function fixtureModule(fixture) {
  return [
    '// Generated by scripts/generate-lldp-fixtures.mjs. Do not edit manually.',
    `export const nodes = ${JSON.stringify(fixture.nodes, null, 2)};`,
    `export const links = ${JSON.stringify(fixture.links, null, 2)};`,
    `export const meta = ${JSON.stringify(fixture.meta, null, 2)};`,
    '',
  ].join('\n');
}

async function main() {
  const datasets = await readJson(resolve(sourceDir, 'datasets.json'));
  if (!Array.isArray(datasets)) {
    throw new TypeError('data/lldp/datasets.json must contain an array.');
  }
  const maasEnrichment = await readOptionalJson(maasEnrichmentPath);

  await rm(outputDir, { recursive: true, force: true });
  await mkdir(outputDir, { recursive: true });

  const index = [];
  for (const dataset of datasets) {
    if (!dataset || typeof dataset.name !== 'string' || typeof dataset.file !== 'string') {
      throw new TypeError('Every LLDP dataset entry must provide string name and file fields.');
    }
    const id = fixtureId(dataset.name);
    const source = await readJson(resolve(sourceDir, dataset.file));
    const fixture = normalizeLldpTopology(source, {
      id,
      name: dataset.name,
      maasEnrichment,
    });
    const filename = `${id}.js`;
    await writeFile(resolve(outputDir, filename), fixtureModule(fixture));
    index.push({
      id,
      label: dataset.name,
      subtitle: `${fixture.meta.diagnostics.sourceNodes} nodes`,
      path: `./data/generated/lldp/${filename}`,
    });
    console.log(
      `[lldp] ${dataset.name}: ${fixture.meta.diagnostics.sourceNodes} source nodes, ` +
      `${fixture.meta.diagnostics.physicalLinks} physical links, ` +
      `${fixture.meta.diagnostics.renderedNodes} rendered nodes, ` +
      `${fixture.meta.diagnostics.maasMatchedNodes} MAAS matches`
    );
  }

  await writeFile(
    resolve(outputDir, 'index.js'),
    [
      '// Generated by scripts/generate-lldp-fixtures.mjs. Do not edit manually.',
      `export const fixtures = ${JSON.stringify(index, null, 2)};`,
      '',
    ].join('\n')
  );
}

main().catch(error => {
  console.error(`[lldp] Fixture generation failed: ${error.message}`);
  process.exitCode = 1;
});
